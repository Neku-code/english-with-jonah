const url = (query = '') => new URL('http://localhost/admin' + query);
const fails = (p: Promise<unknown>, code: string) => assert.rejects(p, (e: unknown) => e instanceof ServiceError && e.code === code);
const input = (revision: number, points: string, feedback = 'Teacher feedback') => ({ requestId: randomUUID(), expectedRevision: String(revision), points, feedback });
async function submitted(studentId: string, f: Awaited<ReturnType<typeof fixture>>, response?: string) {
  const a = await startAttempt(store.db, studentId, f.lesson.id);
  if (response !== undefined) await saveAnswer(store.db, studentId, a.id, { questionId: f.question.id, response, expectedRevision: 0 });
  await submitAttempt(store.db, studentId, a.id); return a;
}
