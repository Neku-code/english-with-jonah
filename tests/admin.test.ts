test('review revisions preserve automatic results, reject stale/out-of-range grades and recalculate completion atomically', async () => {
  const { db, pool } = store;
  const teacher = await createTeacherSession(db), s = await createStudent(db, 'Written review fixture');
  const f = await fixture(db, { manual: true, policy: { mode: 'score', minimumPercent: 90 } });
  const a = await submitted(s.id, f, 'Original written response');
  const originalActivity = (await db.select().from(students).where(eq(students.id, s.id)))[0].lastLearningAt;
  await fails(saveReview(db, teacher.id, a.id, f.question.id, input(0, '11')), 'INVALID_POINTS');
  const first = input(0, '9');
  const saved = await Promise.all([saveReview(db, teacher.id, a.id, f.question.id, first), saveReview(db, teacher.id, a.id, f.question.id, first)]);
  assert.equal(saved[0].id, saved[1].id);
  assert.equal((await db.select().from(teacherReviews).where(eq(teacherReviews.attemptId, a.id))).length, 1);
  assert.equal((await loadAttempt(db, s.id, a.id)).earnedPoints, 9);
  assert.equal((await db.select().from(lessonProgress).where(eq(lessonProgress.studentId, s.id))).length, 1);
  await fails(saveReview(db, teacher.id, a.id, f.question.id, input(0, '5')), 'STALE_REVIEW');
  await saveReview(db, teacher.id, a.id, f.question.id, input(1, '5', 'Amended'));
  assert.equal((await db.select().from(lessonProgress).where(eq(lessonProgress.studentId, s.id))).length, 0);
  const [original] = await db.select().from(answers).where(and(eq(answers.attemptId, a.id), eq(answers.questionId, f.question.id)));
  assert.equal(original.response, 'Original written response'); assert.equal(original.reviewStatus, 'pending'); assert.equal(original.earnedPoints, null);
  assert.equal((await attemptDetail(db, a.id)).reviews.length, 2);
  assert.deepEqual((await db.select().from(students).where(eq(students.id, s.id)))[0].lastLearningAt, originalActivity);
  await saveReview(db, teacher.id, a.id, f.question.id, input(2, '', 'Feedback only'));
  assert.equal((await loadAttempt(db, s.id, a.id)).pendingReview, true);
  assert.equal((await reviewQueue(db, url(`?student=${s.id}`))).rows.length, 1);
  await pool.query("CREATE FUNCTION fail_review_progress() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'test rollback'; END $$; CREATE TRIGGER fail_review_progress BEFORE INSERT ON lesson_progress FOR EACH ROW EXECUTE FUNCTION fail_review_progress()");
  try { await assert.rejects(saveReview(db, teacher.id, a.id, f.question.id, input(3, '10'))); }
  finally { await pool.query('DROP TRIGGER fail_review_progress ON lesson_progress; DROP FUNCTION fail_review_progress()'); }
  assert.equal((await attemptDetail(db, a.id)).reviews.length, 3);
  assert.equal((await loadAttempt(db, s.id, a.id)).pendingReview, true);
  await assert.rejects(db.update(answers).set({ response: 'overwrite' }).where(eq(answers.attemptId, a.id)));
  await assert.rejects(db.update(teacherReviews).set({ feedback: 'overwrite' }).where(eq(teacherReviews.attemptId, a.id)));
  await assert.rejects(db.update(lessonAttempts).set({ earnedPoints: 10 }).where(eq(lessonAttempts.id, a.id)));
});
test('reviewed final exams use existing 90 percent mastery rules and retries never duplicate points', async () => {
  const { db } = store;
  const s = await createStudent(db, 'Mastery review fixture'), teacher = await createTeacherSession(db);
  const f = await fixture(db); await submitted(s.id, f, 'token');
  const exam = await fixture(db, { kind: 'final_exam', unitId: f.unit.id, manual: true });
  const a = await submitted(s.id, exam, 'Exam response');
  await saveReview(db, teacher.id, a.id, exam.question.id, input(0, '9'));
  assert.equal((await homeData(db, s.id)).units.find(u => u.id === f.unit.id)?.points, 100);
  const retry = await submitted(s.id, exam, 'Retry response');
  await saveReview(db, teacher.id, retry.id, exam.question.id, input(0, '8'));
  assert.equal((await homeData(db, s.id)).units.find(u => u.id === f.unit.id)?.points, 100);
  await saveReview(db, teacher.id, a.id, exam.question.id, input(1, '8'));
  assert.equal((await homeData(db, s.id)).units.find(u => u.id === f.unit.id)?.points, 50);
});
test('question statistics use first submitted attempt per student/version, separate blank/pending and preserve version prompts', async () => {
  const { db } = store, teacher = await createTeacherSession(db);
  const s1 = await createStudent(db, 'Statistic fixture A'), s2 = await createStudent(db, 'Statistic fixture B'), s3 = await createStudent(db, 'Statistic fixture C');
  const f = await fixture(db);
  const old = await submitted(s1.id, f, 'wrong'); await submitted(s1.id, f, 'token');
  await submitted(s2.id, f, 'token'); await submitted(s3.id, f);
  const fresh = await newRevision(db, f.lesson.id); const retry = await startAttempt(db, s1.id, f.lesson.id); await submitAttempt(db, s1.id, retry.id);
  const result = await questionPerformance(db, url(`?lesson=${f.lesson.id}`));
  const first = result.rows.find(r => r.questionId === f.question.id)!;
  assert.equal(first.correct, 1); assert.equal(first.incorrect, 1); assert.equal(first.graded, 2); assert.equal(Number(first.percent), 50); assert.equal(first.unanswered, 1); assert.equal(first.pending, 0);
  assert.equal(result.rows.find(r => r.questionId === fresh.question.id)?.unanswered, 1);
  assert.equal((await attemptDetail(db, old.id)).questions[0].content?.prompt, 'Synthetic token');
  const writing = await fixture(db, { manual: true }); const a = await submitted(s1.id, writing, 'Pending response');
  let pending = (await questionPerformance(db, url(`?lesson=${writing.lesson.id}`))).rows[0];
  assert.equal(pending.pending, 1); assert.equal(pending.graded, 0); assert.equal(pending.percent, null);
  await saveReview(db, teacher.id, a.id, writing.question.id, input(0, '5'));
  pending = (await questionPerformance(db, url(`?lesson=${writing.lesson.id}`))).rows[0];
  assert.equal(pending.incorrect, 1); assert.equal(pending.pending, 0); assert.equal(Number(pending.percent), 100);
});
test('structured blank responses stay unanswered and pending authored responses can be reviewed using their stored version', async () => {
  const { db } = store, s = await createStudent(db, 'Structured teacher fixture'), teacher = await createTeacherSession(db);
  const f = await fixture(db, { published: false });
  const task = { kind: 'task' as const, id: 'synthetic-task', number: 1, prompt: 'Synthetic structured prompt', control: 'text' as const, parts: [{ id: 'part', label: 'Synthetic field' }], maxPoints: 10, listening: false };
  await db.update(questions).set({ content: { prompt: task.prompt, task }, grading: { mode: 'authored', accepted: ['synthetic expected phrase'], kind: 'text', partIds: ['part'], feedback: '', notes: '', rubric: null, listening: false, strict: false } }).where(eq(questions.id, f.question.id));
  await db.update(lessons).set({ status: 'published' }).where(eq(lessons.id, f.lesson.id));
  await db.update(lessonVersions).set({ publishedAt: new Date() }).where(eq(lessonVersions.id, f.version.id));
  await submitted(s.id, f, JSON.stringify({ part: '' }));
  const stats = (await questionPerformance(db, url(`?lesson=${f.lesson.id}`))).rows[0];
  assert.equal(stats.unanswered, 1); assert.equal(stats.graded, 0);
  const other = await createStudent(db, 'Structured teacher fixture other');
  const a = await submitted(other.id, f, JSON.stringify({ part: 'an uncertain synthetic phrase' }));
  assert.equal((await loadAttempt(db, other.id, a.id)).pendingReview, true);
  assert.equal((await reviewQueue(db, url(`?lesson=${f.lesson.id}`))).rows.length, 1);
  await saveReview(db, teacher.id, a.id, f.question.id, input(0, '10'));
  const updated = (await questionPerformance(db, url(`?lesson=${f.lesson.id}`))).rows[0];
  assert.equal(updated.correct, 1); assert.equal(updated.unanswered, 1); assert.equal(updated.pending, 0);
});
